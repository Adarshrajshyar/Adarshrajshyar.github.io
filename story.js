/* =========================================================
   🔎 GET STORY BY ID
   ========================================================= */

function getStoryById(id) {

  return storyData.find(
    item => item.id === id
  ) || null;

}


/* =========================================================
   📂 GET STORIES BY CATEGORY
   ========================================================= */

function getStoriesByCategory(category) {

  if (!category || category === "All") {
    return [...storyData];
  }

  return storyData.filter(
    item =>
      String(item.category).toLowerCase() ===
      String(category).toLowerCase()
  );

}


/* =========================================================
   🔍 SEARCH STORY / POETRY
   ========================================================= */

function searchStories(query) {

  const searchText =
    String(query || "")
      .trim()
      .toLowerCase();

  if (!searchText) {
    return [...storyData];
  }

  return storyData.filter(item =>

    String(item.title)
      .toLowerCase()
      .includes(searchText)

    ||

    String(item.text)
      .toLowerCase()
      .includes(searchText)

    ||

    String(item.author)
      .toLowerCase()
      .includes(searchText)

    ||

    String(item.category)
      .toLowerCase()
      .includes(searchText)

  );

}


