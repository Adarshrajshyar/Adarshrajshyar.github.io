/* Find Shayari by ID */

function getShayariById(id) {

  return shayariData.find(
    item => item.id === id
  ) || null;

}


/* Get Shayari by Category */

function getShayariByCategory(category) {

  if (!category || category === "All") {
    return [...shayariData];
  }

  return shayariData.filter(
    item =>
      item.category.toLowerCase() ===
      category.toLowerCase()
  );

}


/* Search Shayari */

function searchShayari(query) {

  const searchText =
    String(query || "")
      .trim()
      .toLowerCase();

  if (!searchText) {
    return [...shayariData];
  }

  return shayariData.filter(item =>

    String(item.title)
      .toLowerCase()
      .includes(searchText)

    ||

    String(item.text)
      .toLowerCase()
      .includes(searchText)

    ||

    String(item.author)
      .toLowerCase()
      .includes(searchText)

    ||

    String(item.category)
      .toLowerCase()
      .includes(searchText)

  );

}


